    # 抓出前面的純數字索書號
    match = re.match(r'^(\d+)', cleaned_number)
    if not match:
        return "索書號格式不正確 (Incorrect Call Number Format)"

    call_number = match.group(1)

    # 取百位數當作主分類 key
    if len(call_number) >= 1:
        first_digit = call_number[0]
    else:
        return "索書號過短 (Call Number Too Short)"

    # 主分類與子分類對應
    main_part = main_category_map.get(first_digit, "未知主分類 (Unknown Main Category)")
    sub_part = subcategory_map.get(call_number, "未知子分類 (Unknown Subcategory)")

    return f"{main_part}_{sub_part}"

